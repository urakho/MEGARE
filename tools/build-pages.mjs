import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'pages-dist');
const marker = path.join(output, '.generated-by-build-pages');
const stableRevision = 'cbbd6c0fcba945dbab941ce2a8e115e2f988cefe';
const testCode = 'MEGARE-TEST-2026';
const git = (...args) => execFileSync('git', [
    '-c', `safe.directory=${root.replaceAll('\\', '/')}`, ...args
], { cwd: root, maxBuffer: 100 * 1024 * 1024 });

function write(relativePath, data) {
    const destination = path.join(output, relativePath);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, data);
}

function copyTree(source, destination, transform) {
    for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
        const from = path.join(source, entry.name);
        const to = path.join(destination, entry.name);
        if (entry.isDirectory()) {
            copyTree(from, to, transform);
        } else if (entry.isFile()) {
            fs.mkdirSync(path.dirname(to), { recursive: true });
            if (transform && entry.name.endsWith('.js')) {
                fs.writeFileSync(to, transform(fs.readFileSync(from, 'utf8')));
            } else {
                fs.copyFileSync(from, to);
            }
        }
    }
}

if (!fs.existsSync(path.join(root, 'index.html')) || !fs.existsSync(path.join(root, 'src', 'main.js'))) {
    throw new Error('Run the Pages build from the MEGARE game repository.');
}
if (fs.existsSync(output)) {
    if (fs.lstatSync(output).isSymbolicLink() || !fs.existsSync(marker)) {
        throw new Error('Refusing to replace a Pages directory not created by this build script.');
    }
    fs.rmSync(output, { recursive: true, force: true });
}
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(marker, 'Generated by tools/build-pages.mjs\n');

const oldPaths = git('ls-tree', '-r', '--name-only', stableRevision, '--',
    'index.html', 'style.css', 'src', 'png', 'music', 'svg')
    .toString('utf8').trim().split(/\r?\n/).filter(Boolean);
for (const oldPath of oldPaths) {
    let data = git('show', `${stableRevision}:${oldPath}`);
    if (oldPath === 'src/main.js') {
        const source = data.toString('utf8');
        const anchor = "const code = (input.value || '').trim();";
        if (!source.includes(anchor)) throw new Error('The stable promo handler has changed.');
        data = Buffer.from(source.replace(anchor, `${anchor}
        if (code === '${testCode}') {
            window.location.assign(new URL('test/', window.location.href).href);
            return;
        }`));
    }
    write(oldPath, data);
}

const testRoot = path.join(output, 'test');
const testIndex = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const firstScript = '<script src="src/pause-menu.js"></script>';
if (!testIndex.includes(firstScript)) throw new Error('The test entry point has changed.');
for (const [, scriptPath] of testIndex.matchAll(/<script\s+src="(src\/[^\"]+)"/g)) {
    if (!fs.existsSync(path.join(root, scriptPath))) {
        throw new Error(`Missing test game script: ${scriptPath}`);
    }
}
write('test/index.html', testIndex.replace(firstScript,
    '<script src="test-storage.js"></script>\n' + firstScript));
write('test/style.css', fs.readFileSync(path.join(root, 'style.css')));
copyTree(path.join(root, 'src'), path.join(testRoot, 'src'), source =>
    source.replace(/\blocalStorage\b/g, 'window.testLocalStorage'));
for (const assetDir of ['png', 'music', 'svg']) {
    copyTree(path.join(root, assetDir), path.join(testRoot, assetDir));
}

write('test/test-storage.js', `// Keep test saves separate from the published game.
(() => {
    const storage = window.localStorage;
    const prefix = 'megare-test:';
    const marker = prefix + '__initialized';
    if (!storage.getItem(marker)) {
        const keys = [];
        for (let i = 0; i < storage.length; i++) {
            const key = storage.key(i);
            if (key && !key.startsWith(prefix)) keys.push(key);
        }
        for (const key of keys) storage.setItem(prefix + key, storage.getItem(key));
        storage.setItem(marker, '1');
    }
    window.testLocalStorage = {
        getItem(key) { return storage.getItem(prefix + key); },
        setItem(key, value) { storage.setItem(prefix + key, value); },
        removeItem(key) { storage.removeItem(prefix + key); },
        clear() {
            const keys = [];
            for (let i = 0; i < storage.length; i++) {
                const key = storage.key(i);
                if (key && key.startsWith(prefix) && key !== marker) keys.push(key);
            }
            for (const key of keys) storage.removeItem(key);
        }
    };
})();
`);
write('.nojekyll', '');
console.log(`Built stable ${stableRevision} and test working tree in ${output}`);
